#!/usr/bin/env bash
# Generates, for every cmd/pg-connector-<name> binary of this Go module, the
# committed nix fileset filesets/pg-connector-<name>.nix: the non-test source
# files of the binary's in-module import closure (`go list -deps`), as a nix
# list of module-root-relative path strings. Each pg-connector-<name>.nix builds
# its mkGoApp `src` from that file, so a derivation hash changes only when a
# package the binary imports changes (a test edit, or an edit to a package it
# does not import, changes nothing). The closure cannot be computed at nix eval
# time (that would be import-from-derivation, which this repo bans), hence the
# committed files, kept current by the `pg-connector-filesets` pre-commit hook.
#
# Usage: gen-filesets.sh [--check | --fixer] [MODULE_DIR]
#   (default)  rewrite the filesets; prints the files it changed.
#   --check    write nothing; print a diff and exit 1 when a committed fileset
#              is stale, missing or orphaned.
#   --fixer    write mode for `pg-hooks fix`: ignores every further argument (the
#              staged file paths the fixer runner appends) and works on
#              <git toplevel>/packages/pg-connector.
# MODULE_DIR defaults to the directory this script lives in.
#
# Never calls nix. Uses the `go` on PATH with GOTOOLCHAIN=local and GOPROXY=off;
# external modules need not be downloaded (`go list -e` tolerates them, and only
# in-module packages are kept). Both GOOS values the packages build on are
# unioned, because meta.platforms = platforms.all.
set -euo pipefail

mode="write"
if [ "${1:-}" = "--check" ]; then
  mode="check"
  shift
fi
if [ "${1:-}" = "--fixer" ]; then
  module_dir="$(git rev-parse --show-toplevel)/packages/pg-connector"
  set --
  set -- "$module_dir"
fi
module_dir="$(cd "${1:-$(dirname "${BASH_SOURCE[0]}")}" && pwd -P)"
cd "$module_dir"

export GOTOOLCHAIN=local GOPROXY=off GOWORK=off GOFLAGS=-mod=readonly CGO_ENABLED=0

out_dir="$module_dir/filesets"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/new"

# One line per in-module package: its directory, then each non-test file.
# shellcheck disable=SC2016 # the template is a go-template, not shell
tmpl='{{if .Module}}{{if .Module.Main}}{{$d := .Dir}}{{range .GoFiles}}{{$d}}/{{.}}
{{end}}{{range .CgoFiles}}{{$d}}/{{.}}
{{end}}{{range .CFiles}}{{$d}}/{{.}}
{{end}}{{range .CXXFiles}}{{$d}}/{{.}}
{{end}}{{range .HFiles}}{{$d}}/{{.}}
{{end}}{{range .SFiles}}{{$d}}/{{.}}
{{end}}{{range .SysoFiles}}{{$d}}/{{.}}
{{end}}{{range .IgnoredGoFiles}}{{$d}}/{{.}}
{{end}}{{range .EmbedFiles}}{{$d}}/{{.}}
{{end}}{{end}}{{end}}'

binaries=()
for d in cmd/pg-connector-*/; do
  [ -d "$d" ] || continue
  binaries+=("$(basename "$d")")
done
if [ "${#binaries[@]}" -eq 0 ]; then
  echo "gen-filesets: no cmd/pg-connector-* binaries under $module_dir" >&2
  exit 2
fi

for b in "${binaries[@]}"; do
  {
    for goos in linux darwin; do
      GOOS=$goos go list -e -deps -f "$tmpl" "./cmd/$b"
    done
  } | while IFS= read -r p; do
    [ -n "$p" ] || continue
    rel="${p#"$module_dir"/}"
    case "$rel" in
    *_test.go | */testdata/*) continue ;;
    esac
    printf '%s\n' "$rel"
  done | LC_ALL=C sort -u >"$tmp/$b.list"
  if [ ! -s "$tmp/$b.list" ]; then
    echo "gen-filesets: empty import closure for cmd/$b (go list failed?)" >&2
    exit 2
  fi
  {
    printf '%s\n' "# Generated by ../gen-filesets.sh from \`go list -deps ./cmd/$b\`; do not edit."
    printf '%s\n' "# Regenerate with: packages/pg-connector/gen-filesets.sh (the pg-connector-filesets"
    printf '%s\n' "# pre-commit hook fails when this file is stale)."
    printf '[\n'
    while IFS= read -r rel; do
      printf '  "%s"\n' "$rel"
    done <"$tmp/$b.list"
    printf ']\n'
  } >"$tmp/new/$b.nix"
done

status=0
if [ "$mode" = check ]; then
  for b in "${binaries[@]}"; do
    if [ ! -f "$out_dir/$b.nix" ]; then
      echo "gen-filesets: filesets/$b.nix is missing" >&2
      status=1
    elif ! diff -u "$out_dir/$b.nix" "$tmp/new/$b.nix" >&2; then
      status=1
    fi
  done
  if [ -d "$out_dir" ]; then
    for f in "$out_dir"/*.nix; do
      [ -e "$f" ] || continue
      name="$(basename "$f" .nix)"
      if [ ! -f "$tmp/new/$name.nix" ]; then
        echo "gen-filesets: filesets/$name.nix has no cmd/$name binary (orphaned)" >&2
        status=1
      fi
    done
  fi
  if [ "$status" -ne 0 ]; then
    echo "gen-filesets: committed filesets are stale. Run: $module_dir/gen-filesets.sh   (or: git add <files>; pg-hooks fix)" >&2
  fi
  exit "$status"
fi

mkdir -p "$out_dir"
for b in "${binaries[@]}"; do
  if [ ! -f "$out_dir/$b.nix" ] || ! cmp -s "$out_dir/$b.nix" "$tmp/new/$b.nix"; then
    cp -f "$tmp/new/$b.nix" "$out_dir/$b.nix"
    echo "gen-filesets: wrote filesets/$b.nix"
  fi
done
for f in "$out_dir"/*.nix; do
  [ -e "$f" ] || continue
  name="$(basename "$f" .nix)"
  if [ ! -f "$tmp/new/$name.nix" ]; then
    rm -f "$f"
    echo "gen-filesets: removed orphaned filesets/$name.nix"
  fi
done
